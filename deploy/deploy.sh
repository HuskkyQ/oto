#!/usr/bin/env bash
# One-command deploy: TeslaMate + the Oto API on a single Docker host.
# Re-running it is safe: it keeps the existing .env and only restarts services.
set -euo pipefail

cd "$(dirname "$0")"

ENV_FILE=.env
COMPOSE=(docker compose -f compose.yml --env-file "$ENV_FILE")

die() { echo "error: $*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "the docker compose plugin is required"

random() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

value_of() {
  sed -n "s/^$1=//p" "$ENV_FILE" | tail -1
}

if [ ! -f "$ENV_FILE" ]; then
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy.sh. Keep this file private: it holds every secret.
ENCRYPTION_KEY=$(random 32)
DATABASE_PASS=$(random 24)
RO_PASSWORD=$(random 24)
API_TOKEN=$(random 32)
TESLAMATE_PORT=4000
GRAFANA_PORT=3000
API_PORT=8080
EOF
  echo "wrote $ENV_FILE with generated secrets"
else
  echo "reusing existing $ENV_FILE"
fi

for key in ENCRYPTION_KEY DATABASE_PASS RO_PASSWORD API_TOKEN; do
  [ -n "$(value_of "$key")" ] || die "$ENV_FILE has no $key"
done

echo "starting postgres"
"${COMPOSE[@]}" up -d database

ready=""
for _ in $(seq 1 60); do
  if "${COMPOSE[@]}" exec -T database pg_isready -U teslamate -d teslamate >/dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 2
done
[ -n "$ready" ] || die "postgres did not become ready"

echo "creating the read-only role"
"${COMPOSE[@]}" exec -T database psql -U teslamate -d teslamate \
  -v ON_ERROR_STOP=1 -v pw="$(value_of RO_PASSWORD)" <<'SQL'
SELECT format('CREATE ROLE teslamate_ro LOGIN PASSWORD %L', :'pw')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'teslamate_ro')\gexec
SELECT format('ALTER ROLE teslamate_ro PASSWORD %L', :'pw')\gexec
GRANT CONNECT ON DATABASE teslamate TO teslamate_ro;
GRANT USAGE ON SCHEMA public TO teslamate_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO teslamate_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO teslamate_ro;
SQL

echo "starting teslamate, grafana and the api"
"${COMPOSE[@]}" up -d --build

cat <<EOF

Done.

  TeslaMate   http://127.0.0.1:$(value_of TESLAMATE_PORT)   (onboard your car here)
  Grafana     http://127.0.0.1:$(value_of GRAFANA_PORT)
  Oto API     http://127.0.0.1:$(value_of API_PORT)

All three bind to loopback only. From your own machine:
  ssh -N -L $(value_of TESLAMATE_PORT):127.0.0.1:$(value_of TESLAMATE_PORT) \\
         -L $(value_of GRAFANA_PORT):127.0.0.1:$(value_of GRAFANA_PORT) \\
         -L $(value_of API_PORT):127.0.0.1:$(value_of API_PORT) user@this-server

Oto needs a URL the phone can reach. Either put an HTTPS reverse proxy in front of
the API, or expose it over Tailscale/WireGuard. Set it in the app's Settings
together with this token:

  $(value_of API_TOKEN)

Next: open TeslaMate, sign in with your Tesla tokens, then use the app.
EOF
